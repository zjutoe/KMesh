    def test_synthetic_same_split_containment_recomputed(self):
        """A synthetic report whose only change is a same-split contained
        list shrink (CJC -> self-only) must yield a recomputed summary and
        matrix: 143/63 edges, train diagonal 71, all other cells unchanged.
        A mutant that hardcodes containment_edges=144 and the 72/36/36
        matrix literals fails here."""
        def standin():
            base = mcp.audit_motif_candidates()
            rep = copy.deepcopy(base)
            _row_by_id(rep, "CJC")["contained_ids"] = ["CJC"]
            return rep

        old = getattr(mcs, "audit_motif_candidates")
        try:
            mcs.audit_motif_candidates = standin
            cat = mcs.build_motif_split_catalogue()
        finally:
            mcs.audit_motif_candidates = old
        assert next(r["contained_ids"]
                    for r in cat["candidates"] if r["id"] == "CJC") == ["CJC"]
