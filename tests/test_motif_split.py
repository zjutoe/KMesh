class TestExceptionPropagation:
    def test_upstream_exception_propagates(self):
        exc = LogicValidationError("split_upstream_fail")
        cause = RuntimeError("split_cause_marker")
        ctx = LogicValidationError("split_context_marker")
        exc.__cause__ = cause
        exc.__context__ = ctx
        msg_before = str(exc)
        seen = {"n": 0}

        def fake(*a, **kw):
            seen["n"] += 1
            raise exc

        old = getattr(mcs, "audit_motif_candidates")
        buf = io.StringIO()
        old_stdout = sys.stdout
        sys.stdout = buf
        try:
            mcs.audit_motif_candidates = fake
            with pytest.raises(LogicValidationError) as excinfo:
                mcs.build_motif_split_catalogue()
        finally:
            sys.stdout = old_stdout
            mcs.audit_motif_candidates = old
        assert seen["n"] == 1, seen
        assert excinfo.value is exc
        assert str(excinfo.value) == msg_before
        assert excinfo.value.__cause__ is cause
        assert excinfo.value.__context__ is ctx
        assert buf.getvalue() == ""


