def _child_env():
    env = dict(os.environ)
    env.pop("PYTHONPATH", None)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["CUDA_VISIBLE_DEVICES"] = ""
    env["PYTEST_DISABLE_PLUGIN_AUTOLOAD"] = "1"
    return env


def _child_script(src, body, tail=None, footer_asserts=True):
    """Assemble the -I -B child: worktree src first, resolved product path,
    a forbidden-import blocker, and a sys.modules scan.  The shared header
    always asserts that both the kmesh package root and the target module
    realpath to this worktree, so every child (including the failure-path
    script) checks them before the body runs."""
    src_str = str(src)
    split_real = str(src / "kmesh" / "logic" / "motif_split.py")
    types_real = str(src / "kmesh" / "logic" / "types.py")
    kmesh_real = str(src / "kmesh" / "__init__.py")
    header = f"""import sys, os, importlib
sys.path.insert(0, {src_str!r})
import kmesh
assert os.path.realpath(kmesh.__file__) == {kmesh_real!r}, kmesh.__file__
import kmesh.logic.types as _kt
assert os.path.realpath(_kt.__file__) == {types_real!r}, _kt.__file__
FORBIDDEN = ('torch', 'yaml', 'kmesh.logic.engine',
            'kmesh.logic.reference_engine')
class BlockFinder:
    def find_spec(self, fullname, path=None, target=None):
        for f in FORBIDDEN:
            if fullname == f or fullname.startswith(f + '.'):
                raise ImportError('forbidden-import: ' + fullname)
        return None
sys.meta_path.insert(0, BlockFinder())
def _assert_blocked(name):
    try:
        importlib.import_module(name)
    except ImportError as e:
        assert 'forbidden-import: ' in str(e), (name, e)
        return
    raise AssertionError('forbidden ' + name + ' imported despite blocker')
for name in FORBIDDEN + ('torch.sub', 'kmesh.logic.engine.sub',
                         'kmesh.logic.reference_engine.sub'):
    _assert_blocked(name)
import kmesh.logic.motif_split as _pm
assert os.path.realpath(_pm.__file__) == {split_real!r}, _pm.__file__
assert _pm.__spec__ is not None, _pm.__spec__
assert os.path.realpath(_pm.__spec__.origin) == {split_real!r}, _pm.__spec__.origin
def _bad():
    return [n for n in sys.modules if any(
        n == f or n.startswith(f + '.') for f in FORBIDDEN)]
before = _bad()
assert before == [], before
"""
    if footer_asserts:
        footer = (
            "assert _bad() == before, _bad()\n"
            "assert isinstance(sys.meta_path[0], BlockFinder)\n"
        )
        if tail:
            footer += f"print('{tail}')\n"
    else:
        footer = ""
    return header + body + footer


class TestDeterminismAndIsolation:
    def test_repeated_calls_independent(self):
        base_snapshot = json.loads(
            json.dumps(mcs.build_motif_split_catalogue(), ensure_ascii=False))
        a = mcs.build_motif_split_catalogue()
        b = mcs.build_motif_split_catalogue()
        assert a == base_snapshot
        assert b == base_snapshot
        assert a is not b
        # mutate one returned catalogue (including nested containers); a fresh
        # build must be unaffected (independent copies, not a shared report).
        a["candidates"][0]["contained_ids"].append("MUT")
        a["candidates"][0]["clauses"][0]["body"].append(_atom("z", "a", "b"))
        a["candidates"][0]["motif_key"].append(999)
        a["summary"]["candidate_count"] = 0
        c = mcs.build_motif_split_catalogue()
        d = mcs.build_motif_split_catalogue()
        assert c == base_snapshot
        assert d == base_snapshot

    def test_subprocess_byte_identical_and_valid_json(self):
        repo_root = Path(__file__).resolve().parents[1]
        src = repo_root / "src"
        split_real = str(src / "kmesh" / "logic" / "motif_split.py")
        env = _child_env()
        script = _child_script(
            src,
            "import runpy\n"
            "import warnings\n"
            "with warnings.catch_warnings():\n"
            "    warnings.filterwarnings('ignore', message=\".+' found in sys\\\\.modules after import of package\")\n"
            "    ns = runpy.run_module('kmesh.logic.motif_split', run_name='__main__')\n"
            "assert ns['__name__'] == '__main__', ns['__name__']\n"
            "spec = ns['__spec__']\n"
            "assert spec is not None, spec\n"
            f"assert os.path.realpath(spec.origin) == {split_real!r}, spec.origin\n",
            tail=None,
        )
        pyc_before = {str(p) for p in src.rglob("*.pyc")}
        out1 = subprocess.run([sys.executable, "-I", "-B", "-c", script],
                              env=env, capture_output=True, text=False,
                              timeout=600)
        out2 = subprocess.run([sys.executable, "-I", "-B", "-c", script],
                              env=env, capture_output=True, text=False,
                              timeout=600)
        assert out1.returncode == 0, out1.stderr
        assert out2.returncode == 0, out2.stderr
        assert out1.stdout == out2.stdout
        assert out1.stderr == b""
        assert out1.stdout.endswith(b"\n")
        cli = json.loads(out1.stdout.decode("utf-8"))
        assert cli == mcs.build_motif_split_catalogue()
        assert cli["schema_version"] == "motif_split_catalogue_v1"
        assert cli["summary"]["candidate_count"] == 80
        pyc_after = {str(p) for p in src.rglob("*.pyc")}
        assert pyc_after == pyc_before, \
            f"new pyc: {sorted(pyc_after - pyc_before)}"

