        assert rows["CJC"]["contained_ids"] == ["CJ", "CJC"]
        assert "JC" not in rows["CJC"]["contained_ids"]
        # complete (non-empty) full keys, not just counts.
        assert rows["CJ"]["motif_key"]
        assert rows["CJC"]["motif_key"] != rows["CJ"]["motif_key"]

