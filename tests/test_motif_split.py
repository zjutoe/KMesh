# JSON <-> object reconstruction helpers (independent oracle).
# ---------------------------------------------------------------------------
def _atom(pred: str, x: str, y: str) -> Atom:
    return Atom(pred, (x, y))


def _fact(pred: str, x: str, y: str) -> Clause:
    return Clause((), _atom(pred, x, y))


def _copy_clause(src: str, dst: str) -> Clause:
    return Clause((_atom(src, "?x", "?y"),), _atom(dst, "?x", "?y"))


def _inv_clause(src: str, dst: str) -> Clause:
    return Clause((_atom(src, "?x", "?y"),), _atom(dst, "?y", "?x"))


def _join_clause(src: str, side: str, dst: str) -> Clause:
    return Clause(
        (_atom(src, "?x", "?y"), _atom(side, "?y", "?z")),
        _atom(dst, "?x", "?z"),
    )


def _inter_clause(src: str, side: str, dst: str) -> Clause:
    return Clause(
        (_atom(src, "?x", "?y"), _atom(side, "?x", "?y")),
        _atom(dst, "?x", "?y"),
    )


def _from_json_atom(obj) -> Atom:
    return Atom(obj["pred"], tuple(obj["args"]))


def _from_json_clause(obj) -> Clause:
    return Clause(
        tuple(_from_json_atom(a) for a in obj["body"]),
        _from_json_atom(obj["head"]),
    )


def _from_json_step(obj) -> ProofStep:
    return ProofStep(obj["clause_index"], tuple(obj["premise_steps"]),
                     _from_json_atom(obj["conclusion"]))


def _reconstruct_row(row) -> tuple:
    clauses = tuple(_from_json_clause(c) for c in row["clauses"])
    query = _from_json_atom(row["query"])
    proof = tuple(_from_json_step(s) for s in row["proof"])
    return clauses, query, proof


def _key_to_json(key) -> object:
    if isinstance(key, tuple):
        return [_key_to_json(x) for x in key]
    return key


def _key_to_tuple(obj) -> object:
    if isinstance(obj, list):
        return tuple(_key_to_tuple(x) for x in obj)
    return obj


