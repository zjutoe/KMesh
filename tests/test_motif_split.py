    def test_bad_bucket_rejected(self):
        """Shift a 2-letter row to a neighbouring in-table (depth, steps)
        bucket by lengthening its proof (and its proof_steps); the per-set
        (depth, steps) counts then disagree with the protocol table and must
        be rejected.  (The real (2,3)/(2,4) rows already fill those table
        cells, so moving a row out breaks the literal counts.)"""
        def mutate(r):
            row = _row_by_id(r, "CC")
            # keep proof_steps consistent with proof length, but move the row
            # into an out-of-table bucket by giving it a 4th step.
            row["proof"] = row["proof"] + [_step_json({
                "clause_index": 3,
                "premise_steps": (2,),
                "conclusion": {"pred": "p3", "args": ["e0", "e1"]},
            })]
            row["proof_steps"] = 4
            row["minimum_depth"] = 2
        _expect_reject(mutate)


