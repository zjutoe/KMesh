class TestWitnessAndMeasurementPreserved:
    def test_rows_preserve_t0019_fields(self, catalogue, real_report):
        """The 80 catalogue rows are the 80 T0019 rows plus a split field:
        every field is value-identical, in the same order."""
        assert len(catalogue["candidates"]) == len(real_report["candidates"])
        for cat_row, rep_row in zip(catalogue["candidates"],
                                    real_report["candidates"]):
            for field in ("id", "clauses", "query", "proof",
                          "motif_key", "minimum_depth",
                          "canonical_proof_count", "proof_steps",
                          "contained_ids"):
                assert cat_row[field] == rep_row[field], field
            assert set(cat_row) == set(rep_row) | {"split"}
            assert isinstance(cat_row["split"], str)

    def test_full_witness_reconstruct_and_verify(self, catalogue):
        for row in catalogue["candidates"]:
            clauses, query, proof = _reconstruct_row(row)
            assert verify_proof(clauses, query, proof), row["id"]
            assert proof[-1].conclusion == query
            assert len(proof) == row["proof_steps"], row["id"]

    def test_anchor_witnesses_match(self, catalogue):
        rows = {r["id"]: r for r in catalogue["candidates"]}
        for word, (clauses, query, proof) in ANCHORS.items():
            assert verify_proof(clauses, query, proof), word
            assert proof[-1].conclusion == query
            row = rows[word]
            rc, rq, rp = _reconstruct_row(row)
            assert clauses == rc, word
            assert query == rq, word
            assert proof == rp, word
            key, cnt, depth = _measured(clauses, query, proof)
            assert row["motif_key"] == _key_to_json(key), word
            assert row["canonical_proof_count"] == cnt, word
            assert row["minimum_depth"] == depth, word
            assert row["proof_steps"] == len(proof), word

    def test_cjc_train_anchor_containment(self, catalogue):
        rows = {r["id"]: r for r in catalogue["candidates"]}
        assert rows["CJ"]["split"] == "train"
