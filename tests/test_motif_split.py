# ---------------------------------------------------------------------------
# Rejection tests (mutate a copy of the real report; expect RuntimeError).
# ---------------------------------------------------------------------------
def _expect_reject(mutate):
    """Run the build with a mutated copy of the real audit report; require
    ``RuntimeError(_ERROR)`` (no partial JSON, no retry)."""
    base = mcp.audit_motif_candidates()
    mutated = copy.deepcopy(base)
    mutate(mutated)
    old = getattr(mcs, "audit_motif_candidates")
    buf = io.StringIO()
    old_stdout = sys.stdout
    sys.stdout = buf
    try:
        mcs.audit_motif_candidates = lambda: mutated
        with pytest.raises(RuntimeError,
                           match="motif_split candidate audit violates motif_split_v1"):
            mcs.build_motif_split_catalogue()
    finally:
        sys.stdout = old_stdout
        mcs.audit_motif_candidates = old
    assert buf.getvalue() == ""


def _row_by_id(rep, word):
    return next(r for r in rep["candidates"] if r["id"] == word)


