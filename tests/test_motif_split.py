def _measured(clauses, query, proof):
    return (
        canonical_motif_key(
            clauses, query, proof,
            max_steps=_MAX_PROOF_STEPS, max_orientations=_MAX_ORIENTATIONS,
        ),
        count_canonical_proofs(
            clauses, query,
            max_fact_checks=_MAX_FACT_CHECKS, max_derivations=_MAX_DERIVATIONS,
            max_proof_steps=_MAX_PROOF_STEPS,
        ),
        minimum_proof_depth(
            clauses, query,
            max_fact_checks=_MAX_FACT_CHECKS, max_derivations=_MAX_DERIVATIONS,
        ),
    )


def _step_json(step) -> dict:
    return {"clause_index": step["clause_index"],
            "premise_steps": step["premise_steps"],
            "conclusion": step["conclusion"]}


