class TestIsolationAndContamination:
    def test_no_stdout_on_call(self):
        buf = io.StringIO()
        old = sys.stdout
        sys.stdout = buf
        try:
            mcs.build_motif_split_catalogue()
        finally:
            sys.stdout = old
        assert buf.getvalue() == ""

    def test_dependency_report_not_shared(self):
        base = mcp.audit_motif_candidates()
        row0 = base["candidates"][0]
        snapshot = json.loads(json.dumps(base, ensure_ascii=False))
        old = getattr(mcs, "audit_motif_candidates")
        seen = {"rep": None}

        def spy():
            seen["rep"] = base
            return base

        try:
            mcs.audit_motif_candidates = spy
            cat = mcs.build_motif_split_catalogue()
        finally:
            mcs.audit_motif_candidates = old
        assert seen["rep"] is base
        # top-level row, its nested containers, and its key are all new
        # objects, not the dependency report's.
        assert cat["candidates"][0] is not row0
        assert cat["candidates"][0]["contained_ids"] is not row0["contained_ids"]
        assert cat["candidates"][0]["clauses"] is not row0["clauses"]
        assert cat["candidates"][0]["clauses"][0] is not row0["clauses"][0]
        assert cat["candidates"][0]["motif_key"] is not row0["motif_key"]
        # mutating the catalogue (including nested containers) never mutates
        # the live dependency report.
        cat["candidates"][0]["contained_ids"].append("xx")
        cat["candidates"][0]["clauses"][0]["body"].append(_atom("z", "a", "b"))
        cat["candidates"][0]["motif_key"].append(99)
        assert json.loads(json.dumps(base, ensure_ascii=False)) == snapshot
        cat2 = mcs.build_motif_split_catalogue()
        assert cat2["summary"] == _EXPECTED_SUMMARY

    def test_import_resolves_to_worktree_split(self):
        src = Path(__file__).resolve().parents[1] / "src"
